#!/usr/bin/env node
/* Copy each browser tool's embedded template into templates/, so the server
   fills exactly the precedent the tool itself fills. Re-run after any change to
   a tool's template:  npm run sync-templates */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tools = join(root, '..');

const SOURCES = [
  ['corporate-tools/share-transfer-instrument.html', 'share-transfer-instrument.b64'],
  ['corporate-tools/share-certificate.html', 'share-certificate.b64']
];

for (const [src, out] of SOURCES) {
  const html = await readFile(join(tools, src), 'utf8');
  const m = html.match(/const TEMPLATE_B64 = "([A-Za-z0-9+/=]+)"/);
  if (!m) throw new Error(`TEMPLATE_B64 not found in ${src}`);
  await writeFile(join(root, 'templates', out), m[1]);
  console.log(`${out.padEnd(34)} ${(m[1].length / 1024).toFixed(0)} KB  ← ${src}`);
}

/* Attorney appointment (v2): the page carries its two templates, their field
   geometry and the TH SarabunPSK widths as one JSON block, and the fill engine
   as the script right after it. Both are copied as they are — the server runs
   the page's own engine, so the two cannot drift apart. The preview images and
   page positions are browser-only and are left behind. */
{
  const src = 'document-automation/attorney-appointment.html';
  const html = await readFile(join(tools, src), 'utf8');
  const data = html.match(/<script id="poa-data" type="application\/json">([\s\S]*?)<\/script>/);
  if (!data) throw new Error(`poa-data not found in ${src}`);
  const d = JSON.parse(data[1]);
  const keep = { spec: d.spec, widths: d.widths, tpl: d.tpl };
  await writeFile(join(root, 'templates', 'attorney-appointment.json'), JSON.stringify(keep));
  console.log(`${'attorney-appointment.json'.padEnd(34)} ${(JSON.stringify(keep).length / 1024).toFixed(0)} KB  ← ${src}`);

  const after = html.slice(html.indexOf(data[0]) + data[0].length);
  const eng = after.match(/<script>\s*([\s\S]*?POAEngine[\s\S]*?)<\/script>/);
  if (!eng || !/makeEngine/.test(eng[1])) throw new Error(`fill engine not found in ${src}`);
  await writeFile(join(root, 'src', 'poa-engine.cjs'),
    `/* GENERATED by scripts/extract-templates.mjs from ${src} — do not edit here;\n` +
    `   the source is document-automation/_build/attorney-appointment/poa-engine.js. */\n` + eng[1].trim() + '\n');
  console.log(`${'src/poa-engine.cjs'.padEnd(34)} ${(eng[1].length / 1024).toFixed(0)} KB  ← ${src}`);
}

/* Power of attorney to sue (หนังสือมอบอำนาจให้ฟ้องคดี): the page carries its
   template fragments, the measured signature geometry and the package as one
   JSON block, and the engine as the script right after it — copied as they
   are, so the server builds exactly the document the page exports. */
{
  const src = 'document-automation/power-of-attorney.html';
  const html = await readFile(join(tools, src), 'utf8');
  const data = html.match(/<script id="pwa-data" type="application\/json">([\s\S]*?)<\/script>/);
  if (!data) throw new Error(`pwa-data not found in ${src}`);
  const d = JSON.parse(data[1]);
  const keep = { frags: d.frags, alt: d.alt, geom: d.geom, tpl: d.tpl };
  await writeFile(join(root, 'templates', 'power-of-attorney.json'), JSON.stringify(keep));
  console.log(`${'power-of-attorney.json'.padEnd(34)} ${(JSON.stringify(keep).length / 1024).toFixed(0)} KB  ← ${src}`);

  const after = html.slice(html.indexOf(data[0]) + data[0].length);
  const eng = after.match(/<script>\s*([\s\S]*?PWAEngine[\s\S]*?)<\/script>/);
  if (!eng || !/fromInput/.test(eng[1])) throw new Error(`fill engine not found in ${src}`);
  await writeFile(join(root, 'src', 'pwa-engine.cjs'),
    `/* GENERATED by scripts/extract-templates.mjs from ${src} — do not edit here;\n` +
    `   the source is document-automation/_build/power-of-attorney/pwa-engine.js. */\n` + eng[1].trim() + '\n');
  console.log(`${'src/pwa-engine.cjs'.padEnd(34)} ${(eng[1].length / 1024).toFixed(0)} KB  ← ${src}`);
}
